import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const outputPath = resolve(here, 'manifest.generated.ts');
const temporaryDirectory = await mkdtemp(join(tmpdir(), 'opentools-kernel-'));
const adapterBundle = resolve(temporaryDirectory, 'adapters.cjs');
const require = createRequire(import.meta.url);

try {
  await build({
    entryPoints: [resolve(here, 'adapters/index.ts')],
    outfile: adapterBundle,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    alias: { '@': root },
    logLevel: 'silent',
  });
  const { ALL_ADAPTER_OPERATIONS } = require(adapterBundle);
  const manifest = ALL_ADAPTER_OPERATIONS.map((operation) => ({
    id: operation.id,
    source: operation.source,
    name: operation.name,
    description: operation.description,
    input: operation.input,
    params: operation.params,
    output: operation.output,
    runtime: operation.runtime,
    deterministic: operation.deterministic,
    ...(operation.notice ? { notice: operation.notice } : {}),
  }));
  const source = `// Generated by lib/kernel/generate-manifest.mjs. Do not edit by hand.\nimport type { KernelOperationDescriptor } from './types';\n\nexport const KERNEL_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies readonly KernelOperationDescriptor[];\n`;
  await writeFile(outputPath, source, 'utf8');
  process.stdout.write(
    `Wrote ${manifest.length} operations to ${outputPath}\n`,
  );
} finally {
  await rm(temporaryDirectory, { recursive: true, force: true });
}
